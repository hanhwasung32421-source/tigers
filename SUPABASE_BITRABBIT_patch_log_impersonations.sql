create table if not exists public.bitduck_log_impersonations (
  id bigint generated by default as identity primary key,
  admin_local_user_id bigint not null,
  target_local_user_id bigint not null,
  target_username text,
  ip text,
  user_agent text,
  created_at timestamptz not null default now()
);

create index if not exists idx_bitduck_log_impersonations_created_at
  on public.bitduck_log_impersonations(created_at desc);

alter table public.bitduck_log_impersonations enable row level security;
