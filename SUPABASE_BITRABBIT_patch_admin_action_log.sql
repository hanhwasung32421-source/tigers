create table if not exists public.bitrabbit_log_admin_actions (
  id bigint generated by default as identity primary key,
  admin_local_user_id bigint not null,
  action text not null,
  target_type text,
  target_id text,
  detail jsonb,
  ip text,
  user_agent text,
  created_at timestamptz not null default now()
);

create index if not exists idx_bitrabbit_log_admin_actions_created_at
  on public.bitrabbit_log_admin_actions(created_at desc);
create index if not exists idx_bitrabbit_log_admin_actions_admin
  on public.bitrabbit_log_admin_actions(admin_local_user_id, created_at desc);

alter table public.bitrabbit_log_admin_actions enable row level security;
