-- CSP(Content-Security-Policy) Report-Only 위반 보고를 서버에 기록하는 테이블입니다.
-- 브라우저 콘솔은 아무도 안 보고 있으니, 실사용자 트래픽에서 뭔가 깨지면 여기 쌓입니다.
-- 며칠 지켜보고 비어있으면 강제 적용(enforce)으로 전환해도 안전하다는 뜻입니다.
-- 실행: Supabase 대시보드 > SQL Editor에서 이 파일 내용을 붙여넣고 실행하세요.

create table if not exists public.bitrabbit_log_csp_reports (
  id bigint generated by default as identity primary key,
  blocked_uri text,
  violated_directive text,
  document_uri text,
  raw jsonb,
  ip text,
  user_agent text,
  created_at timestamptz not null default now()
);

create index if not exists idx_bitrabbit_log_csp_reports_created_at
  on public.bitrabbit_log_csp_reports(created_at desc);

alter table public.bitrabbit_log_csp_reports enable row level security;
-- 다른 bitrabbit_log_* 테이블과 동일한 패턴: 앱 서버는 항상 service_role 키로 접근하므로
-- anon/authenticated용 정책은 두지 않는다.

